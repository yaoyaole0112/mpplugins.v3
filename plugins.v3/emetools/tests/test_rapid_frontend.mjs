import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'

const source = readFileSync(new URL('../src/Workbench.vue', import.meta.url), 'utf8')
const backend = readFileSync(new URL('../__init__.py', import.meta.url), 'utf8')

test('local rapid upload is available from the shared sidebar and page', () => {
  assert.match(source, /key: 'rapid', title: '本地秒传'/)
  assert.match(source, /active === 'rapid'/)
  assert.match(source, /SHA1/)
  assert.match(source, /Cookie 沿用“115 网盘 STRM 助手”；源目录须在 MoviePilot 容器内可访问/)
  assert.doesNotMatch(source, /<p class="eme-hint">沿用“115 网盘 STRM 助手”/)
  assert.match(source, /rapid\/status/)
  assert.match(source, /rapid\/config/)
  assert.match(source, /rapid\/action/)
  assert.match(source, /browse\('rapid_source'/)
  assert.match(source, /browse\('rapid_target'/)
  assert.match(source, /browse\('rapid_file', index\)/)
  assert.match(source, /execute\(rapidFile \? 'rapid_files'/)
  assert.match(source, /rapidCommand\('run', config\.id, \[file\.path\]\)/)
  assert.match(backend, /self\._rapid\.browse_directory, action\.config_id, action\.path/)
  assert.match(backend, /config_id: str = ""/)
  assert.match(source, /class="eme-folder-error"/)
  assert.match(source, /@click="loadFolder">重试读取/)
  assert.match(source, /silentNotice: operation === 'p115_dirs'/)
  assert.match(source, /<\/nav>\s*<p v-if="p115Tasks\.length[\s\S]*class="eme-message eme-task-status"/)
  assert.doesNotMatch(source, /<\/aside>\s*<p v-if="p115Tasks\.length/)
  assert.match(source, /启用实时监控/)
  assert.match(source, /:disabled="!rapid\.loaded \|\| rapidActionBusy" @click="rapidCommand\('run', config\.id\)"/)
  assert.match(source, /const rapidActionBusy = ref\(false\)/)
  assert.match(source, /if \(rapidActionBusy\.value\) return/)
  assert.doesNotMatch(source, /:disabled="busy \|\| !rapid\.loaded" @click="rapidCommand\('run'/)
  assert.doesNotMatch(source, /rapidConfigDirtyFor\(config\)/)
  assert.match(source, /if \(rapidConfigDirty\.value\) await persistRapidDraft\(\)/)
  assert.match(source, /点击“立即扫描”时会先自动保存配置/)
  assert.match(source, /eme-rapid-switches/)
  assert.match(source, /rapid\.realtime_watched_configs/)
  assert.match(source, /config\.upload_on_unmatched/)
  assert.match(source, /未命中后普通上传到网盘/)
  assert.match(source, /realtime_poll_seconds/)
  assert.match(source, /实时监控优先使用目录事件，不再周期性遍历整个目录/)
  assert.match(source, /realtime_poll_seconds \|\| 300/)
  assert.match(source, /const status = await get\('rapid\/status'\)/)
  assert.match(source, /实时监控未启动：/)
  assert.match(source, /<h3>秒传记录<\/h3>/)
  assert.match(source, /uploaded: '⬆️'/)
  assert.match(source, /const rapidLogsPageSize = 6/)
  assert.match(source, /rapidLogItems/)
  assert.match(source, /aria-label="秒传记录分页"/)
  assert.match(source, /function pollRapidStatus\(\)/)
  assert.match(source, /}, 5000\)/)
  assert.match(source, /\.eme-results\.eme-rapid-logs\{max-height:none;overflow:visible\}/)
  assert.match(source, /class="eme-results eme-rapid-logs eme-rapid-history"/)
  assert.match(source, /\.eme-results\.eme-rapid-history\{display:grid;grid-template-rows:repeat\(6,88px\)\}/)
  assert.match(source, /\.eme-rapid-history \.eme-result\{box-sizing:border-box;height:88px;min-height:88px;align-items:center;overflow:hidden\}/)
  assert.match(source, /\.eme-rapid-history \.eme-result strong,\.eme-rapid-history \.eme-result small\{overflow:hidden;text-overflow:ellipsis;white-space:nowrap\}/)
  assert.match(source, /v-for="\(item, index\) in rapidLogItems"/)
  assert.match(source, /v-if="rapidLogsPageCount > 1" class="eme-pagination" aria-label="秒传记录分页"/)
  assert.doesNotMatch(source, /失败目录未填写时，实际失败文件会继续保留在本地源目录/)
  assert.match(source, /v-if="!rapid\.logs\.length && !rapid\.activity\.length" class="eme-hint">暂无秒传记录/)
})

